def _component(name: str, cost: int) -> ItemComponent:
    return ItemComponent(name=name, cost=cost)


def _item(
    item_id: str,
    name: str,
    cost: int,
    components: list[tuple[str, int]],
    tags: list[str],
    roles: list[Role],
    counters: list[str],
    phases: list[str],
    synergies: list[str] | None = None,
) -> Item:
    return Item(
        id=item_id,
        name=name,
        cost=cost,
        components=[
            _component(component_name, component_cost)
            for component_name, component_cost in components
        ],
        tags=tags,
        roles=roles,
        hero_synergies=synergies or [],
        counters=counters,
        game_phases=phases,
        patch_version=DEMO_VERSION,
        data_notice=DEMO_NOTICE,
    )


